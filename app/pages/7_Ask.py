import os

import pandas as pd
import plotly.express as px
import streamlit as st

from common import annotate, setup
from merchant_pulse import text2sql

setup("Ask", "💬")
st.title("7 · Ask the warehouse")
annotate("Natural language → SQL",
         "A pattern grammar covers the questions merchants actually ask (top stores, sales of an item, alerts by type, stockouts). Anything that "
         "already looks like SQL runs as-is. Every statement passes a read-only guard. With `GEMINI_API_KEY` set, unmatched questions go to Gemini with "
         f"the schema; the SQL still has to pass the guard. Gemini: **{'configured' if os.environ.get('GEMINI_API_KEY') else 'not configured, patterns only'}**.",
         "Gemini on Vertex AI with BigQuery schema grounding (or BigQuery data canvas), behind the Cloud Run `/ask` endpoint with row-level security "
         "so a merchant only sees their own stores.", expanded=True)

examples = ["top 5 stores by revenue last 30 days", "sales of FOODS_3_001 in CA_1 last 14 days", "alerts by type", "which store had the most alerts",
            "units by category last week", "stockouts", "average units on SNAP days vs other days"]
q = st.text_input("Question or SQL", value=st.session_state.get("ask_q", examples[0]))
cols = st.columns(len(examples))
for c, ex in zip(cols, examples):
    if c.button(ex, width="stretch"):
        st.session_state["ask_q"] = ex; st.rerun()
df, sql, how, err = text2sql.run(q)
st.code(sql or "-- no SQL generated", language="sql")
st.caption(f"generated by: {how}")
if err:
    st.warning(err)
elif df is not None:
    st.dataframe(df, hide_index=True, width="stretch", height=300)
    if len(df) and df.shape[1] >= 2 and pd.api.types.is_numeric_dtype(df.iloc[:, -1]) and not pd.api.types.is_numeric_dtype(df.iloc[:, 0]) and len(df) <= 40:
        st.plotly_chart(px.bar(df, x=df.columns[0], y=df.columns[-1], height=300), width="stretch")
    elif len(df) and "date" in df.columns and "units" in df.columns:
        st.plotly_chart(px.line(df, x="date", y="units", color="store_id" if "store_id" in df.columns else None, height=300), width="stretch")
with st.expander("Schema"):
    st.code(text2sql.SCHEMA)
